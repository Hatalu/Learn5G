// ---------- cakes ----------
const SPONGE = '#ffe0a6', CRUST = '#c98a4b', CREAM = '#ff9ec4', CREAM_D = '#e5578d';

// Weights for an obviously unequal cut of d pieces (biggest piece at least ~2x smallest).
export function unequalWeights(d, rnd = Math.random) {
  const w = Array.from({ length: d }, () => 0.5 + rnd());
  w[0] += 1.2;
  return w;
}

function wedge(cx, cy, r, a0, a1) {
  const p = (a) => `${(cx + r * Math.cos(a)).toFixed(1)} ${(cy + r * Math.sin(a)).toFixed(1)}`;
  if (a1 - a0 >= Math.PI * 2 - 1e-6) return `M${cx - r} ${cy} a${r} ${r} 0 1 0 ${2 * r} 0 a${r} ${r} 0 1 0 ${-2 * r} 0`;
  return `M${cx} ${cy} L${p(a0)} A${r} ${r} 0 ${a1 - a0 > Math.PI ? 1 : 0} 1 ${p(a1)} Z`;
}

// Round cake seen from above. on: array of booleans (frosted). gone: slices eaten (drawn as empty plate).
export function roundCake({ d, on = [], gone = [], weights, size = 220, id = '' }) {
  const cx = 110, cy = 104, r = 86;
  const w = weights || Array(d).fill(1), tot = w.reduce((a, b) => a + b, 0);
  let a = -Math.PI / 2, out = '';
  for (let i = 0; i < d; i++) {
    const a1 = a + (w[i] / tot) * Math.PI * 2, mid = (a + a1) / 2;
    const fx = cx + r * 0.58 * Math.cos(mid), fy = cy + r * 0.58 * Math.sin(mid);
    if (gone[i]) { out += `<path d="${wedge(cx, cy, r, a, a1)}" fill="#fff" stroke="#e7d3c0" stroke-width="2" stroke-dasharray="6 5"/>`; a = a1; continue; }
    out += `<g class="slice" data-i="${i}"><path d="${wedge(cx, cy, r, a, a1)}" fill="${on[i] ? CREAM : SPONGE}" stroke="${CRUST}" stroke-width="3" stroke-linejoin="round"/>`;
    if (on[i]) out += `<circle cx="${fx.toFixed(1)}" cy="${fy.toFixed(1)}" r="9" fill="#ff3d6e" stroke="${INK}" stroke-width="2"/><circle cx="${(fx - 3).toFixed(1)}" cy="${(fy - 3).toFixed(1)}" r="2.6" fill="#fff"/>`;
    else out += `<circle cx="${fx.toFixed(1)}" cy="${fy.toFixed(1)}" r="3" fill="${CRUST}" opacity=".5"/>`;
    out += '</g>';
    a = a1;
  }
  return `<svg viewBox="0 0 220 220" width="${size}" height="${size}" data-id="${id}">
    <ellipse cx="110" cy="112" rx="104" ry="100" fill="#fff" stroke="#f1c6d8" stroke-width="5"/>
    <circle cx="110" cy="110" r="90" fill="${CRUST}"/>${out}
    <circle cx="110" cy="104" r="86" fill="none" stroke="${INK}" stroke-width="4"/></svg>`;
}

// Long bar cake seen from the side. Pieces share one total width so bars of different d compare fairly.
export function barCake({ d, on = [], gone = [], weights, width = 420, id = '', label = '' }) {
  const W = 400, x0 = 10, w = weights || Array(d).fill(1), tot = w.reduce((a, b) => a + b, 0);
  let x = x0, out = '';
  for (let i = 0; i < d; i++) {
    const pw = (w[i] / tot) * W;
    if (gone[i]) { out += `<rect x="${x + 2}" y="30" width="${pw - 4}" height="66" rx="6" fill="none" stroke="#e7d3c0" stroke-width="2" stroke-dasharray="6 5"/>`; x += pw; continue; }
    out += `<g class="slice" data-i="${i}">
      <rect x="${x}" y="30" width="${pw}" height="66" fill="${SPONGE}" stroke="${CRUST}" stroke-width="3"/>
      <rect x="${x}" y="58" width="${pw}" height="9" fill="#fff4f8"/>`;
    if (on[i]) out += `<path d="M${x} 30 h${pw} v12 ${Array.from({ length: 3 }, (_, k) => `q-${pw / 12} 12 -${pw / 6} 0 q-${pw / 12} -8 -${pw / 6} 0`).join(' ')} Z" fill="${CREAM}" stroke="${CREAM_D}" stroke-width="2"/>
      <circle cx="${x + pw / 2}" cy="24" r="${Math.min(10, pw / 4)}" fill="#ff3d6e" stroke="${INK}" stroke-width="2"/>`;
    out += '</g>';
    x += pw;
  }
  return `<svg viewBox="0 0 420 ${label ? 130 : 110}" width="${width}" data-id="${id}" style="max-width:100%">
    <rect x="4" y="94" width="412" height="10" rx="5" fill="#fff" stroke="#f1c6d8" stroke-width="3"/>${out}
    <rect x="${x0}" y="30" width="${W}" height="66" fill="none" stroke="${INK}" stroke-width="4" rx="4"/>
    ${label ? `<text x="210" y="124" text-anchor="middle" font-size="18" font-weight="700" fill="${INK}">${label}</text>` : ''}</svg>`;
}

// Cookies split into d plates of k each. sel: array of booleans for every cookie (index plate*k + j).
export function cookieTray({ d, k, sel = [], glow = [] }) {
  const pw = 112, gap = 10, cols = Math.min(d, 4), rows = Math.ceil(d / cols);
  const W = cols * pw + (cols - 1) * gap, ph = 30 + Math.ceil(k / 3) * 34;
  const H = rows * (ph + gap);
  let out = '';
  for (let p = 0; p < d; p++) {
    const px = (p % cols) * (pw + gap), py = Math.floor(p / cols) * (ph + gap);
    out += `<rect class="plate${glow[p] ? ' glow' : ''}" x="${px + 2}" y="${py + 2}" width="${pw - 4}" height="${ph - 4}" rx="18" fill="#fff" stroke="#f1c6d8" stroke-width="4"/>`;
    for (let j = 0; j < k; j++) {
      const i = p * k + j, cx = px + 22 + (j % 3) * 34, cy = py + 30 + Math.floor(j / 3) * 34;
      out += `<g class="cookie${sel[i] ? ' in' : ''}" data-i="${i}"><circle cx="${cx}" cy="${cy}" r="14" fill="${sel[i] ? '#ffcf7a' : '#e8b06a'}" stroke="${INK}" stroke-width="3"/>
        <circle cx="${cx - 5}" cy="${cy - 3}" r="2.6" fill="#6b3b1f"/><circle cx="${cx + 4}" cy="${cy + 4}" r="2.6" fill="#6b3b1f"/><circle cx="${cx + 5}" cy="${cy - 5}" r="2" fill="#6b3b1f"/>
        ${sel[i] ? `<path d="M${cx - 6} ${cy} l4 5 l9 -10" fill="none" stroke="#2fb08c" stroke-width="4" stroke-linecap="round"/>` : ''}</g>`;
    }
  }
  return `<svg viewBox="-4 -4 ${W + 8} ${H + 4}" style="width:min(${W + 8}px,100%);max-height:100%">${out}</svg>`;
}

